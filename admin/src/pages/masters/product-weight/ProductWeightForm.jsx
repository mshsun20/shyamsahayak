import { useState, useEffect, useCallback, useMemo } from "react";
import { useForm } from "react-hook-form";
import { useDispatch } from "react-redux";
import { useNavigate, useParams, Link } from "react-router-dom";
import { ChevronRight } from "lucide-react";
import AdminLayout from "../../../layouts/AdminLayout";
import Loader from "../../../components/Loader";
import axiosInstance from "../../../config/axiosInstance";
import { showSnackbar } from "../../../redux/slices/snackbarSlice";
import {
  API,
  BASE_PATH,
  formatWeight,
  refId,
  productLabel,
  thicknessLabel,
  metricLabel,
  useAllocationMasters,
} from "./productWeightUtils";

const INFO_MAX = 250;

const emptyForm = {
  product: "",
  thickness: "",
  metric: "",
  unitWeight: "",
  info: "",
  status: "",
};

function Label({ children, required }) {
  return (
    <label className="block text-sm font-semibold text-gray-800 mb-2">
      {children} {required && <span className="text-danger">*</span>}
    </label>
  );
}

// Only offer usable master records, but always keep the currently selected one so Edit shows it.
const usable = (list, selectedId, isUsable) =>
  list.filter((item) => item._id === selectedId || isUsable(item));

export default function ProductWeightForm() {
  const { id } = useParams();
  const isEdit = Boolean(id);
  const dispatch = useDispatch();
  const navigate = useNavigate();
  const { products, thicknesses, metrics } = useAllocationMasters();

  const [isLoading, setIsLoading] = useState(false);

  const {
    register,
    handleSubmit,
    watch,
    reset,
    formState: { errors, isSubmitting },
  } = useForm({ defaultValues: emptyForm, mode: "onSubmit" });

  const values = watch();
  const info = values.info || "";

  const productOptions = useMemo(
    () => usable(products, values.product, (p) => p.status !== "Archived"),
    [products, values.product]
  );
  const thicknessOptions = useMemo(
    () => usable(thicknesses, values.thickness, (t) => !t.status || t.status === "Active"),
    [thicknesses, values.thickness]
  );
  const metricOptions = useMemo(
    () => usable(metrics, values.metric, (m) => !m.status || m.status === "Active"),
    [metrics, values.metric]
  );

  const fetchData = useCallback(async () => {
    setIsLoading(true);
    try {
      const response = await axiosInstance.get(`${API}/${id}`);
      const allocation = response?.data?.data;
      if (allocation) {
        reset({
          ...emptyForm,
          product: refId(allocation.product),
          thickness: refId(allocation.thickness),
          metric: refId(allocation.metric),
          unitWeight: allocation.unitWeight != null ? formatWeight(allocation.unitWeight) : "",
          info: allocation.info ?? "",
          status: allocation.status || "Active",
        });
      }
    } catch (error) {
      console.error(error.message);
      dispatch(showSnackbar({ message: error.response?.data?.message || error.message, type: "error" }));
    } finally {
      setIsLoading(false);
    }
  }, [id, reset, dispatch]);

  useEffect(() => {
    if (isEdit) {
      fetchData();
    }
  }, [isEdit, fetchData]);

  const onSubmit = async (data) => {
    // code is generated by the server and never sent
    const payload = {
      product: data.product,
      thickness: data.thickness,
      metric: data.metric,
      unitWeight: Number(data.unitWeight),
      info: data.info?.trim() || "",
      status: data.status,
    };

    try {
      if (isEdit) {
        await axiosInstance.patch(`${API}/${id}`, payload);
      } else {
        await axiosInstance.post(API, payload);
      }
      dispatch(
        showSnackbar({
          message: isEdit
            ? "Product weight allocation updated successfully"
            : "Product weight allocation created successfully",
          type: "success",
        })
      );
      navigate(BASE_PATH);
    } catch (error) {
      console.error(error.message);
      dispatch(showSnackbar({ message: error.response?.data?.message || error.message, type: "error" }));
    }
  };

  const inputClass = (field) =>
    `w-full px-3 py-2.5 text-sm border rounded-lg bg-white focus:outline-none focus:ring-2 focus:ring-primary/30 ${
      errors[field] ? "border-danger" : "border-gray-200 focus:border-primary"
    }`;

  const selectClass = (field) => `${inputClass(field)} ${values[field] ? "text-gray-800" : "text-gray-400"}`;

  const hint = (field, text) =>
    errors[field] ? (
      <p className="text-xs text-danger mt-1">{errors[field].message}</p>
    ) : (
      <p className="text-[11px] text-gray-400 mt-1">{text}</p>
    );

  const crumb = isEdit ? "Edit Allocation" : "Add Allocation";
  const title = isEdit ? "Edit Product Weight Allocation" : "Add Product Weight Allocation";

  return (
    <AdminLayout title="Master Data">
      {isLoading && <Loader />}
      <div className="mb-1">
        <div className="flex items-center gap-1.5 text-xs text-gray-400 mb-1.5">
          <span>Master Data</span>
          <ChevronRight size={12} />
          <Link to={BASE_PATH} className="hover:text-primary">Product Weight Allocation</Link>
          <ChevronRight size={12} />
          <span className="text-gray-600">{crumb}</span>
        </div>
        <h2 className="text-lg font-semibold text-gray-900">{title}</h2>
        <p className="text-xs text-gray-500 mt-1">
          {isEdit
            ? "Update the product weight allocation details."
            : "Create a new product weight allocation for the system."}
        </p>
      </div>

      <form onSubmit={handleSubmit(onSubmit)} className="mt-4 space-y-5" noValidate>
        <div className="bg-white rounded-xl border border-gray-200 overflow-hidden">
          <div className="px-5 py-3 bg-gray-50 border-b border-gray-200">
            <p className="text-sm font-semibold text-gray-900">Product &amp; Attributes</p>
          </div>
          <div className="px-5 py-5 grid grid-cols-1 md:grid-cols-2 gap-x-10 gap-y-5">
            <div>
              <Label required>Product</Label>
              <select {...register("product", { required: "Product is required." })} className={selectClass("product")}>
                <option value="" disabled>
                  Select product
                </option>
                {productOptions.map((p) => (
                  <option key={p._id} value={p._id} className="text-gray-800">
                    {productLabel(p)}
                  </option>
                ))}
              </select>
              {hint("product", "Select product from product master.")}
            </div>

            <div>
              <Label required>Thickness</Label>
              <select
                {...register("thickness", { required: "Thickness is required." })}
                className={selectClass("thickness")}
              >
                <option value="" disabled>
                  Select thickness
                </option>
                {thicknessOptions.map((t) => (
                  <option key={t._id} value={t._id} className="text-gray-800">
                    {thicknessLabel(t)}
                  </option>
                ))}
              </select>
              {hint("thickness", "Select thickness from thickness master.")}
            </div>

            <div>
              <Label required>Metric</Label>
              <select {...register("metric", { required: "Metric is required." })} className={selectClass("metric")}>
                <option value="" disabled>
                  Select metric
                </option>
                {metricOptions.map((m) => (
                  <option key={m._id} value={m._id} className="text-gray-800">
                    {metricLabel(m)}
                  </option>
                ))}
              </select>
              {hint("metric", "Select metric from metric master.")}
            </div>

            <div>
              <Label required>Unit Weight</Label>
              <input
                type="number"
                inputMode="decimal"
                min="0"
                step="0.001"
                placeholder="Enter unit weight"
                {...register("unitWeight", {
                  required: "Unit weight is required.",
                  pattern: { value: /^\d+(\.\d{1,3})?$/, message: "Enter a valid number with up to 3 decimal places." },
                  validate: (v) => Number(v) > 0 || "Unit weight must be greater than 0.",
                })}
                className={inputClass("unitWeight")}
              />
              {hint("unitWeight", "Enter unit weight (up to 3 decimal places). Example: 0.395")}
            </div>
          </div>
        </div>

        <div className="bg-white rounded-xl border border-gray-200 overflow-hidden">
          <div className="px-5 py-3 bg-gray-50 border-b border-gray-200">
            <p className="text-sm font-semibold text-gray-900">Additional Information</p>
          </div>
          <div className="px-5 py-5">
            <Label>Info</Label>
            <div className="relative">
              <textarea
                rows={3}
                maxLength={INFO_MAX}
                placeholder="Enter additional information (optional)"
                {...register("info", {
                  maxLength: { value: INFO_MAX, message: `Maximum ${INFO_MAX} characters.` },
                })}
                className={`${inputClass("info")} resize-none pb-6`}
              />
              <span className="absolute right-3 bottom-2.5 text-[11px] text-gray-400">
                {info.length}/{INFO_MAX}
              </span>
            </div>
            {hint("info", "Provide any additional information about this allocation.")}
          </div>
        </div>

        <div className="bg-white rounded-xl border border-gray-200 overflow-hidden">
          <div className="px-5 py-3 bg-gray-50 border-b border-gray-200">
            <p className="text-sm font-semibold text-gray-900">{isEdit ? "Status & Date" : "Status"}</p>
          </div>
          <div className="px-5 py-5">
            {isEdit ? (
              <div>
                <Label required>Status</Label>
                <select {...register("status", { required: "Status is required." })} className={selectClass("status")}>
                  <option value="" disabled>
                    Select status
                  </option>
                  <option value="Active" className="text-gray-800">Active</option>
                  <option value="Inactive" className="text-gray-800">Inactive</option>
                </select>
                {hint("status", "Select the status for this allocation.")}
              </div>
            ) : (
              <div className="flex flex-col sm:flex-row sm:items-start gap-2 sm:gap-6">
                <label className="sm:w-28 shrink-0 text-sm font-semibold text-gray-800 sm:pt-2.5">
                  Status <span className="text-danger">*</span>
                </label>
                <div className="flex-1 min-w-0">
                  <select {...register("status", { required: "Status is required." })} className={selectClass("status")}>
                    <option value="" disabled>
                      Select status
                    </option>
                    <option value="Active" className="text-gray-800">Active</option>
                    <option value="Inactive" className="text-gray-800">Inactive</option>
                  </select>
                  {hint("status", "Select the status for this allocation.")}
                </div>
              </div>
            )}
          </div>
        </div>

        <div className="flex items-center justify-end gap-3">
          <button
            type="button"
            onClick={() => navigate(BASE_PATH)}
            className="px-6 py-2.5 text-sm font-medium text-gray-700 bg-white border border-gray-200 rounded-lg hover:bg-gray-50"
          >
            Cancel
          </button>
          <button
            type="submit"
            disabled={isSubmitting}
            className="px-6 py-2.5 text-sm font-medium text-white bg-primary rounded-lg hover:bg-primary-dark disabled:opacity-60"
          >
            {isSubmitting ? (isEdit ? "Updating..." : "Saving...") : isEdit ? "Update" : "Save"}
          </button>
        </div>
      </form>
    </AdminLayout>
  );
}
