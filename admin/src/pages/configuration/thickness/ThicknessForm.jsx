import { useState, useEffect, useCallback } from "react";
import { useForm } from "react-hook-form";
import { useDispatch } from "react-redux";
import { useNavigate, useParams, Link } from "react-router-dom";
import { ChevronRight } from "lucide-react";
import AdminLayout from "../../../layouts/AdminLayout";
import Loader from "../../../components/Loader";
import axiosInstance from "../../../config/axiosInstance";
import { showSnackbar } from "../../../redux/slices/snackbarSlice";
import { thicknessUnits } from "../../../data/configuration";
import { formatValue } from "./thicknessUtils";

const DETAILS_MAX = 250;

const emptyForm = {
  code: "",
  value: "",
  unit: "",
  details: "",
  status: "Active",
};

function FieldRow({ label, required, hint, children }) {
  return (
    <div className="flex flex-col sm:flex-row sm:items-start gap-2 sm:gap-6">
      <label className="sm:w-44 shrink-0 text-sm font-semibold text-gray-800 sm:pt-2.5">
        {label} {required && <span className="text-danger">*</span>}
      </label>
      <div className="flex-1 min-w-0">
        {children}
        {hint}
      </div>
    </div>
  );
}

export default function ThicknessForm() {
  const { id } = useParams();
  const isEdit = Boolean(id);
  const dispatch = useDispatch();
  const navigate = useNavigate();

  const [isLoading, setIsLoading] = useState(false);
  // keep a unit coming from the API selectable even if it is not in the static list
  const [unitOptions, setUnitOptions] = useState(thicknessUnits);

  const {
    register,
    handleSubmit,
    watch,
    reset,
    formState: { errors, isSubmitting },
  } = useForm({ defaultValues: emptyForm, mode: "onSubmit" });

  const details = watch("details") || "";
  const unit = watch("unit");

  const fetchData = useCallback(async () => {
    setIsLoading(true);
    try {
      const response = await axiosInstance.get(`/thicknesses/${id}`);
      const thickness = response?.data?.data;
      if (thickness) {
        if (thickness.unit) {
          setUnitOptions((prev) => (prev.includes(thickness.unit) ? prev : [...prev, thickness.unit]));
        }
        reset({
          ...emptyForm,
          code: thickness.code ?? "",
          value: thickness.value != null ? formatValue(thickness.value) : "",
          unit: thickness.unit ?? "",
          details: thickness.details ?? "",
          status: thickness.status || "Active",
        });
      }
    } catch (error) {
      console.error(error.message);
      dispatch(showSnackbar({ message: error.response?.data?.message || error.message, type: "error" }));
    } finally {
      setIsLoading(false);
    }
  }, [id, reset, dispatch]);

  useEffect(() => {
    if (isEdit) {
      fetchData();
    }
  }, [isEdit, fetchData]);

  const onSubmit = async (data) => {
    // code is generated by the server and never sent
    const payload = {
      value: Number(data.value),
      unit: data.unit,
      details: data.details?.trim() || "",
      status: data.status,
    };

    try {
      if (isEdit) {
        await axiosInstance.patch(`/thicknesses/${id}`, payload);
      } else {
        await axiosInstance.post(`/thicknesses`, payload);
      }
      dispatch(
        showSnackbar({
          message: isEdit ? "Thickness updated successfully" : "Thickness created successfully",
          type: "success",
        })
      );
      navigate("/thickness-master");
    } catch (error) {
      console.error(error.message);
      dispatch(showSnackbar({ message: error.response?.data?.message || error.message, type: "error" }));
    }
  };

  const inputClass = (field) =>
    `w-full px-3 py-2.5 text-sm border rounded-lg bg-white focus:outline-none focus:ring-2 focus:ring-primary/30 ${
      errors[field] ? "border-danger" : "border-gray-200 focus:border-primary"
    }`;

  const hint = (field, text) =>
    errors[field] ? (
      <p className="text-xs text-danger mt-1">{errors[field].message}</p>
    ) : (
      <p className="text-[11px] text-gray-400 mt-1">{text}</p>
    );

  const title = isEdit ? "Edit Thickness" : "Add Thickness";

  return (
    <AdminLayout title="Configuration">
      {isLoading && <Loader />}
      <div className="mb-1">
        <div className="flex items-center gap-1.5 text-xs text-gray-400 mb-1.5">
          <span>Configuration</span>
          <ChevronRight size={12} />
          <Link to="/thickness-master" className="hover:text-primary">Thickness Master</Link>
          <ChevronRight size={12} />
          <span className="text-gray-600">{title}</span>
        </div>
        <h2 className="text-lg font-semibold text-gray-900">{title}</h2>
        <p className="text-xs text-gray-500 mt-1">
          {isEdit ? "Update the thickness value to be used in system." : "Create a new thickness value to be used in system."}
        </p>
      </div>

      <form onSubmit={handleSubmit(onSubmit)} className="mt-4 space-y-5" noValidate>
        <div className="bg-white rounded-xl border border-gray-200 overflow-hidden">
          <div className="px-5 py-3 bg-gray-50 border-b border-gray-200">
            <p className="text-sm font-semibold text-gray-900">Thickness Details</p>
          </div>
          <div className="px-5 py-5 space-y-5">
            {isEdit && (
              <FieldRow label="Code" hint={hint("code", "Thickness code is auto-generated and cannot be changed.")}>
                <input
                  {...register("code")}
                  disabled
                  className="w-full px-3 py-2.5 text-sm border border-gray-200 rounded-lg bg-gray-50 text-gray-500 cursor-not-allowed"
                />
              </FieldRow>
            )}

            <FieldRow
              label="Value"
              required
              hint={hint("value", "Enter thickness value (upto 2 decimal places). Example: 0.50")}
            >
              <input
                type="number"
                inputMode="decimal"
                min="0"
                step="0.01"
                placeholder="Enter thickness value"
                {...register("value", {
                  required: "Thickness value is required.",
                  pattern: { value: /^\d+(\.\d{1,2})?$/, message: "Enter a valid number with up to 2 decimal places." },
                  validate: (v) => Number(v) > 0 || "Thickness value must be greater than 0.",
                })}
                className={inputClass("value")}
              />
            </FieldRow>

            <FieldRow label="Unit" required hint={hint("unit", "Select the unit for thickness (e.g. mm, gm, inch).")}>
              <select
                {...register("unit", { required: "Unit is required." })}
                className={`${inputClass("unit")} ${unit ? "text-gray-800" : "text-gray-400"}`}
              >
                <option value="" disabled>
                  Select unit
                </option>
                {unitOptions.map((u) => (
                  <option key={u} value={u} className="text-gray-800">
                    {u}
                  </option>
                ))}
              </select>
            </FieldRow>

            <FieldRow label="Details">
              <div className="relative">
                <textarea
                  rows={3}
                  maxLength={DETAILS_MAX}
                  placeholder="Enter details (optional)"
                  {...register("details", {
                    maxLength: { value: DETAILS_MAX, message: `Maximum ${DETAILS_MAX} characters.` },
                  })}
                  className={`${inputClass("details")} resize-none pb-6`}
                />
                <span className="absolute right-3 bottom-2.5 text-[11px] text-gray-400">
                  {details.length}/{DETAILS_MAX}
                </span>
              </div>
              {errors.details && <p className="text-xs text-danger mt-1">{errors.details.message}</p>}
            </FieldRow>
          </div>
        </div>

        <div className="bg-white rounded-xl border border-gray-200 overflow-hidden">
          <div className="px-5 py-3 bg-gray-50 border-b border-gray-200">
            <p className="text-sm font-semibold text-gray-900">Status</p>
          </div>
          <div className="px-5 py-5">
            <FieldRow label="Status" required hint={hint("status", "Select the status for this thickness value.")}>
              <select {...register("status", { required: true })} className={inputClass("status")}>
                <option value="Active">Active</option>
                <option value="Inactive">Inactive</option>
              </select>
            </FieldRow>

            <div className="flex items-center justify-end gap-3 mt-6 pt-5 border-t border-gray-100">
              <button
                type="button"
                onClick={() => navigate("/thickness-master")}
                className="px-6 py-2.5 text-sm font-medium text-gray-700 bg-white border border-gray-200 rounded-lg hover:bg-gray-50"
              >
                Cancel
              </button>
              <button
                type="submit"
                disabled={isSubmitting}
                className="px-6 py-2.5 text-sm font-medium text-white bg-primary rounded-lg hover:bg-primary-dark disabled:opacity-60"
              >
                {isSubmitting ? "Saving..." : isEdit ? "Save Changes" : "Save"}
              </button>
            </div>
          </div>
        </div>
      </form>
    </AdminLayout>
  );
}
