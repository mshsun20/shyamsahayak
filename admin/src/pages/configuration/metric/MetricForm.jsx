import { useState, useEffect, useCallback } from "react";
import { useForm } from "react-hook-form";
import { useDispatch } from "react-redux";
import { useNavigate, useParams, Link } from "react-router-dom";
import { ChevronRight } from "lucide-react";
import AdminLayout from "../../../layouts/AdminLayout";
import Loader from "../../../components/Loader";
import axiosInstance from "../../../config/axiosInstance";
import { showSnackbar } from "../../../redux/slices/snackbarSlice";

const DETAILS_MAX = 250;

const emptyForm = {
  value: "",
  details: "",
  status: "",
};

function FieldRow({ label, required, hint, children }) {
  return (
    <div className="flex flex-col sm:flex-row sm:items-start gap-2 sm:gap-6">
      <label className="sm:w-44 shrink-0 text-sm font-semibold text-gray-800 sm:pt-2.5">
        {label} {required && <span className="text-danger">*</span>}
      </label>
      <div className="flex-1 min-w-0">
        {children}
        {hint}
      </div>
    </div>
  );
}

export default function MetricForm() {
  const { id } = useParams();
  const isEdit = Boolean(id);
  const dispatch = useDispatch();
  const navigate = useNavigate();

  const [isLoading, setIsLoading] = useState(false);

  const {
    register,
    handleSubmit,
    watch,
    reset,
    formState: { errors, isSubmitting },
  } = useForm({ defaultValues: emptyForm, mode: "onSubmit" });

  const details = watch("details") || "";
  const status = watch("status");

  const fetchData = useCallback(async () => {
    setIsLoading(true);
    try {
      const response = await axiosInstance.get(`/metrics/${id}`);
      const metric = response?.data?.data;
      if (metric) {
        reset({
          ...emptyForm,
          value: metric.value != null ? String(metric.value) : "",
          details: metric.details ?? "",
          status: metric.status || "Active",
        });
      }
    } catch (error) {
      console.error(error.message);
      dispatch(showSnackbar({ message: error.response?.data?.message || error.message, type: "error" }));
    } finally {
      setIsLoading(false);
    }
  }, [id, reset, dispatch]);

  useEffect(() => {
    if (isEdit) {
      fetchData();
    }
  }, [isEdit, fetchData]);

  const onSubmit = async (data) => {
    // code is generated by the server and never sent
    const payload = {
      value: data.value.trim(),
      details: data.details?.trim() || "",
      status: data.status,
    };

    try {
      if (isEdit) {
        await axiosInstance.patch(`/metrics/${id}`, payload);
      } else {
        await axiosInstance.post(`/metrics`, payload);
      }
      dispatch(
        showSnackbar({
          message: isEdit ? "Metric updated successfully" : "Metric created successfully",
          type: "success",
        })
      );
      navigate("/metric-master");
    } catch (error) {
      console.error(error.message);
      dispatch(showSnackbar({ message: error.response?.data?.message || error.message, type: "error" }));
    }
  };

  const inputClass = (field) =>
    `w-full px-3 py-2.5 text-sm border rounded-lg bg-white focus:outline-none focus:ring-2 focus:ring-primary/30 ${
      errors[field] ? "border-danger" : "border-gray-200 focus:border-primary"
    }`;

  const hint = (field, text) =>
    errors[field] ? (
      <p className="text-xs text-danger mt-1">{errors[field].message}</p>
    ) : (
      <p className="text-[11px] text-gray-400 mt-1">{text}</p>
    );

  const title = isEdit ? "Edit Metric" : "Add Metric";

  const actions = (
    <div className="flex items-center justify-end gap-3">
      <button
        type="button"
        onClick={() => navigate("/metric-master")}
        className="px-6 py-2.5 text-sm font-medium text-gray-700 bg-white border border-gray-200 rounded-lg hover:bg-gray-50"
      >
        Cancel
      </button>
      <button
        type="submit"
        disabled={isSubmitting}
        className="px-6 py-2.5 text-sm font-medium text-white bg-primary rounded-lg hover:bg-primary-dark disabled:opacity-60"
      >
        {isSubmitting ? (isEdit ? "Updating..." : "Saving...") : isEdit ? "Update" : "Save"}
      </button>
    </div>
  );

  return (
    <AdminLayout title="Configuration">
      {isLoading && <Loader />}
      <div className="mb-1">
        <div className="flex items-center gap-1.5 text-xs text-gray-400 mb-1.5">
          <span>Configuration</span>
          <ChevronRight size={12} />
          <Link to="/metric-master" className="hover:text-primary">Metric Master</Link>
          <ChevronRight size={12} />
          <span className="text-gray-600">{title}</span>
        </div>
        <h2 className="text-lg font-semibold text-gray-900">{title}</h2>
        <p className="text-xs text-gray-500 mt-1">
          {isEdit ? "Update the metric details." : "Create a new metric to be used in the system."}
        </p>
      </div>

      <form onSubmit={handleSubmit(onSubmit)} className="mt-4 space-y-5" noValidate>
        <div className="bg-white rounded-xl border border-gray-200 overflow-hidden">
          <div className="px-5 py-3 bg-gray-50 border-b border-gray-200">
            <p className="text-sm font-semibold text-gray-900">Metric Details</p>
          </div>
          <div className="px-5 py-5 space-y-5">
            <FieldRow label="Value" required hint={hint("value", "Enter the metric. Example: RMT")}>
              <input
                type="text"
                placeholder="Enter value"
                {...register("value", {
                  required: "Metric value is required.",
                  validate: (v) => v.trim().length > 0 || "Metric value is required.",
                })}
                className={inputClass("value")}
              />
            </FieldRow>

            <FieldRow label="Details">
              <div className="relative">
                <textarea
                  rows={3}
                  maxLength={DETAILS_MAX}
                  placeholder="Enter details (optional)"
                  {...register("details", {
                    maxLength: { value: DETAILS_MAX, message: `Maximum ${DETAILS_MAX} characters.` },
                  })}
                  className={`${inputClass("details")} resize-none pb-6`}
                />
                <span className="absolute right-3 bottom-2.5 text-[11px] text-gray-400">
                  {details.length}/{DETAILS_MAX}
                </span>
              </div>
              {errors.details ? (
                <p className="text-xs text-danger mt-1">{errors.details.message}</p>
              ) : (
                <p className="text-[11px] text-gray-400 mt-1">Provide additional information about this metric.</p>
              )}
            </FieldRow>
          </div>
        </div>

        <div className="bg-white rounded-xl border border-gray-200 overflow-hidden">
          <div className="px-5 py-3 bg-gray-50 border-b border-gray-200">
            <p className="text-sm font-semibold text-gray-900">Status</p>
          </div>
          <div className="px-5 py-5">
            <FieldRow label="Status" required hint={hint("status", "Select the status for this metric.")}>
              <select
                {...register("status", { required: "Status is required." })}
                className={`${inputClass("status")} ${status ? "text-gray-800" : "text-gray-400"}`}
              >
                <option value="" disabled>
                  Select status
                </option>
                <option value="Active" className="text-gray-800">Active</option>
                <option value="Inactive" className="text-gray-800">Inactive</option>
              </select>
            </FieldRow>

            {/* Edit design keeps the buttons inside the Status card */}
            {isEdit && <div className="mt-6 pt-5 border-t border-gray-100">{actions}</div>}
          </div>
        </div>

        {/* Add design places the buttons below the cards */}
        {!isEdit && actions}
      </form>
    </AdminLayout>
  );
}
